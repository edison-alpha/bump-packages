#!/usr/bin/env node
// Copies the code the app shares with the backend into bump/lib/bump/, so the frontend builds without importing from
// outside its own folder while both sides still run one definition:
//
//   lib/bump/shared/    @bump/shared without the zod request schemas (server-side validation only)
//   lib/bump/dreamdex/  @bump/dreamdex's browser half: config, units, orders, errors (not fills/reader: server only)
//
// Imports are rewritten for the app (no .ts suffixes, @bump/shared → ../shared). Run after any change to those
// packages, together with export-api-types.mjs:
//
//   node scripts/export-frontend.mjs

import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = resolve(ROOT, "../bump/lib/bump");

const header = (pkg, file) => `// Generated by bump-packages/scripts/export-frontend.mjs from bump-packages/${pkg}/src/${file}.
// Do not edit here: change the package and rerun the script, so bump-backend and bump keep one definition.
`;

const rewrite = (source) =>
  source
    .replace(/from "@bump\/shared"/g, 'from "../shared"')
    .replace(/from "(\.{1,2}\/[^"]+)\.ts"/g, 'from "$1"');

const PACKAGES = {
  shared: ["types", "markets", "format", "calc", "progress"],
  dreamdex: ["config", "units", "orders", "errors"],
};

rmSync(TARGET, { recursive: true, force: true });
for (const [pkg, files] of Object.entries(PACKAGES)) {
  const dir = resolve(TARGET, pkg);
  mkdirSync(dir, { recursive: true });
  for (const file of files) {
    writeFileSync(resolve(dir, `${file}.ts`), header(pkg, `${file}.ts`) + rewrite(readFileSync(resolve(ROOT, pkg, "src", `${file}.ts`), "utf8")));
  }
  writeFileSync(resolve(dir, "index.ts"), header(pkg, "index.ts") + files.map((f) => `export * from "./${f}";`).join("\n") + "\n");
  console.log(`wrote ${dir} (${files.join(", ")})`);
}
