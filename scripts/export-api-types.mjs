#!/usr/bin/env node
// Copies the wire types (api-types/src/types.ts) into bump/lib/api/types.ts, so the frontend builds without importing
// from outside its own folder while the backend and frontend still share one definition. Run after any change to
// api-types:
//
//   node scripts/export-api-types.mjs

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = resolve(ROOT, "api-types/src/types.ts");
const TARGET = resolve(ROOT, "../bump/lib/api/types.ts");

const header = `// Generated by bump-packages/scripts/export-api-types.mjs from bump-packages/api-types/src/types.ts.
// Do not edit here: change api-types and rerun the script, so bump-backend and bump keep one definition.
`;
mkdirSync(dirname(TARGET), { recursive: true });
writeFileSync(TARGET, header + readFileSync(SOURCE, "utf8"));
console.log(`wrote ${TARGET}`);
